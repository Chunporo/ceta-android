package com.ceta.cinema.auth

import android.content.Context
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.Firebase
import com.google.firebase.auth.FirebaseUser
import com.google.firebase.auth.actionCodeSettings
import com.google.firebase.auth.GoogleAuthProvider
import com.google.firebase.auth.auth
import com.google.firebase.firestore.firestore
import kotlinx.coroutines.tasks.await

/** Email/password and Google sign-in on Firebase Auth; profile stored at users/{uid} in Firestore. */
class AuthRepository {
    private val auth = Firebase.auth
    private val db = Firebase.firestore

    val currentUser: FirebaseUser? get() = auth.currentUser

    suspend fun signUp(email: String, password: String): FirebaseUser {
        val user = auth.createUserWithEmailAndPassword(email, password).await().user!!
        saveProfile(user)
        return user
    }

    suspend fun signIn(email: String, password: String): FirebaseUser =
        auth.signInWithEmailAndPassword(email, password).await().user!!

    /** [webClientId] is R.string.default_web_client_id (generated by the google-services plugin). */
    suspend fun signInWithGoogle(context: Context, webClientId: String): FirebaseUser {
        val option = GetGoogleIdOption.Builder()
            .setServerClientId(webClientId)
            .setFilterByAuthorizedAccounts(false)
            .build()
        val result = CredentialManager.create(context)
            .getCredential(context, GetCredentialRequest.Builder().addCredentialOption(option).build())
        val cred = result.credential
        require(cred is CustomCredential && cred.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
            "Unexpected credential type"
        }
        val idToken = GoogleIdTokenCredential.createFrom(cred.data).idToken
        val user = auth.signInWithCredential(GoogleAuthProvider.getCredential(idToken, null)).await().user!!
        saveProfile(user)
        return user
    }

    /** Emails a one-time sign-in link; the link opens [LINK_URL] which the app claims as an App Link. */
    suspend fun sendSignInLink(email: String) {
        val settings = actionCodeSettings {
            url = LINK_URL
            handleCodeInApp = true
            setAndroidPackageName("com.ceta.cinema", true, null)
        }
        auth.sendSignInLinkToEmail(email, settings).await()
    }

    fun isSignInLink(link: String): Boolean = auth.isSignInWithEmailLink(link)

    /** [email] must be the address the link was sent to (the user re-types it if it was opened on another device). */
    suspend fun signInWithLink(email: String, link: String): FirebaseUser {
        val user = auth.signInWithEmailLink(email, link).await().user!!
        saveProfile(user)
        return user
    }

    fun signOut() = auth.signOut()

    companion object {
        const val LINK_URL = "https://ceta-dedff.firebaseapp.com/finishSignIn"
    }

    private suspend fun saveProfile(user: FirebaseUser) {
        db.collection("users").document(user.uid)
            .set(mapOf("email" to user.email, "displayName" to user.displayName))
            .await()
    }
}
