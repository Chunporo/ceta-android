package com.ceta.cinema.navigation

object Routes {
    const val ONBOARD = "onboard"
    const val LOGIN = "login"
    const val EMAIL_LOGIN = "login-email"
    const val REGISTER = "register"
    const val FORGOT_PASSWORD = "forgot-password"
    /** The five-tab shell (Home, Cinemas, My tickets, Offers, Account). */
    const val MAIN = "main"
    const val SEARCH = "search"
    const val MOVIE_DETAIL = "movie/{movieId}"
    fun movieDetail(id: String) = "movie/$id"
    const val SHOWTIMES = "showtimes/{movieId}"
    fun showtimes(movieId: String) = "showtimes/$movieId"
    const val SEAT_MAP = "seats/{showtimeId}"
    fun seatMap(showtimeId: Long) = "seats/$showtimeId"
    const val HOLD_EXPIRED = "hold-expired/{showtimeId}?seats={seats}"
    fun holdExpired(showtimeId: Long, seats: List<String>) = "hold-expired/$showtimeId?seats=${android.net.Uri.encode(seats.joinToString(","))}"
    const val TICKET_DETAIL = "tickets/{bookingId}"
    fun ticketDetail(bookingId: Long) = "tickets/$bookingId"
    const val HISTORY = "history"
    const val NOTIFICATIONS = "notifications"
    const val PROFILE = "profile"
    const val VOUCHERS = "vouchers"
    const val REMINDERS = "reminders"
    const val PAYMENT_METHODS = "payment-methods"
    const val HELP = "help"
    const val COMBO = "combo/{bookingId}"
    fun combo(bookingId: Long) = "combo/$bookingId"
    const val PAYMENT_RESULT = "payment/result/{bookingId}?failed={failed}"
    fun paymentResult(bookingId: Long, failed: Boolean = false) = "payment/result/$bookingId?failed=$failed"
    const val PAY_FAIL = "payment/failed/{bookingId}"
    fun payFail(bookingId: Long) = "payment/failed/$bookingId"
    const val VIETQR = "payment/vietqr/{bookingId}?img={img}&note={note}"
    fun vietQr(bookingId: Long, img: String, note: String) = "payment/vietqr/$bookingId?img=${android.net.Uri.encode(img)}&note=${android.net.Uri.encode(note)}"
    const val CHECKOUT = "checkout/{bookingId}"
    fun checkout(bookingId: Long) = "checkout/$bookingId"
}
